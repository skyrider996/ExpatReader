import { test, expect } from '@playwright/test'
import path from 'node:path'

async function openBook(page: any, filename = 'A-small-journey.epub') {
  await page.getByLabel('导入 EPUB', { exact: true }).setInputFiles(path.resolve('tests/fixtures', filename))
  await expect(page.getByLabel('返回书库')).toBeEnabled()
  await expect(page.getByText('正在打开书籍…', { exact: true })).toHaveCount(0)
}
async function savedSection(page: any) {
  return page.evaluate(() => new Promise<number>((resolve, reject) => {
    const request = indexedDB.open('incremental-reader')
    request.onsuccess = () => {
      const database = request.result
      const read = database.transaction('progress').objectStore('progress').getAll()
      read.onsuccess = () => { resolve(read.result[0]?.locator.section); database.close() }
      read.onerror = () => reject(read.error)
    }
    request.onerror = () => reject(request.error)
  }))
}

test('library is separate, searchable, and returns to the same book without duplicate readers', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '我的书库' })).toBeVisible()
  await openBook(page)
  await expect(page.locator('aside')).toHaveCount(0)
  await page.getByLabel('切换侧栏').click()
  await page.getByRole('button', { name: 'Chapter 2', exact: true }).click()
  await expect.poll(() => savedSection(page)).toBe(1)
  await page.getByLabel('返回书库').click()
  await page.getByLabel('搜索书库').fill('不存在的书')
  await expect(page.locator('.book-card')).toHaveCount(0)
  await page.getByLabel('搜索书库').fill('')
  await page.locator('.book-card').click()
  await expect(page.locator('foliate-view')).toHaveCount(1)
  await expect(page.locator('.chapter-label')).toContainText('Chapter 2')
  await page.getByLabel('返回书库').click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '我的书库' })).toBeVisible()
  await page.locator('.book-card').click()
  await expect.poll(() => savedSection(page)).toBe(1)
  await expect(page.locator('.chapter-label')).toContainText('Chapter 2')
  await page.getByLabel('返回书库').click()
  await openBook(page, '另一种结构.epub')
  await page.getByLabel('返回书库').click()
  await expect(page.locator('.book-card')).toHaveCount(2)
  await page.screenshot({ path: '.cache/previews/library-basic.png', fullPage: true })
})

test('typography and themes persist without losing the selected chapter', async ({ page }) => {
  await page.goto('/'); await openBook(page)
  await page.getByLabel('切换侧栏').click()
  await page.getByRole('button', { name: 'Chapter 2', exact: true }).click()
  await expect.poll(() => savedSection(page)).toBe(1)
  await page.getByLabel('阅读排版', { exact: true }).click()
  await page.getByLabel('阅读字体').selectOption('serif')
  await page.getByLabel('阅读行距').fill('2.1')
  await page.getByLabel('阅读宽度').fill('680')
  await page.getByLabel('字号', { exact: true }).fill('24')
  await page.getByLabel('分页栏数').selectOption('2')
  await page.getByRole('button', { name: '夜间', exact: true }).click()
  const frame = page.frames().find(f => f.url().startsWith('blob:'))!
  await expect.poll(() => frame.locator('body').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(32, 33, 36)')
  await expect.poll(() => frame.locator('p').first().evaluate(el => getComputedStyle(el).lineHeight)).toBe('50.4px')
  await expect(page.locator('.chapter-label')).toContainText('Chapter 2')
  await page.reload()
  await expect(page.getByLabel('返回书库')).toBeEnabled()
  await expect(page.locator('.chapter-label')).toContainText('Chapter 2')
  await page.getByLabel('阅读排版', { exact: true }).click()
  await expect(page.getByLabel('阅读行距')).toHaveValue('2.1')
  await expect(page.getByLabel('阅读宽度')).toHaveValue('680')
  await expect(page.getByLabel('阅读字体')).toHaveValue('serif')
  await expect(page.getByRole('button', { name: '夜间', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: '.cache/previews/reader-dark.png', fullPage: true })
  await page.getByRole('button', { name: '恢复默认排版' }).click()
  await expect(page.getByLabel('字号', { exact: true })).toHaveValue('20')
  await expect(page.getByRole('button', { name: '明亮', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('progress navigation, filtered outline, keyboard paging and focus mode work', async ({ page }) => {
  await page.goto('/'); await openBook(page)
  await page.getByLabel('全书阅读进度').fill('100')
  await expect.poll(() => savedSection(page)).toBe(1)
  await page.getByLabel('切换侧栏').click()
  await page.getByLabel('筛选目录').fill('Chapter 2')
  await expect(page.locator('.toc')).toHaveCount(1)
  await expect(page.locator('.toc')).toHaveAttribute('aria-current', 'location')
  await page.getByLabel('筛选目录').fill('')
  await page.getByRole('button', { name: 'Chapter 1', exact: true }).click()
  await expect.poll(() => savedSection(page)).toBe(0)
  await page.getByLabel('专注阅读', { exact: true }).click()
  await expect(page.locator('header')).toBeHidden()
  await page.locator('body').click({ position: { x: 2, y: 200 } })
  const before = Number(await page.getByLabel('全书阅读进度').inputValue())
  await page.keyboard.press('PageDown')
  await expect.poll(async () => Number(await page.getByLabel('全书阅读进度').inputValue())).toBeGreaterThan(before)
  await page.keyboard.press('Escape')
  await expect(page.locator('header')).toBeVisible()
  await page.screenshot({ path: '.cache/previews/reader-basic.png', fullPage: true })
  await page.getByLabel('全书阅读进度').fill('100')
  await expect.poll(() => savedSection(page)).toBe(1)
  await page.getByLabel('切换侧栏').click()
  await page.getByLabel('筛选目录').fill('Chapter')
  await page.getByLabel('筛选目录').press('ArrowLeft')
  await expect.poll(() => savedSection(page)).toBe(1)
  await page.getByLabel('更多工具').click()
  await page.getByRole('button', { name: '切换全屏' }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true)
  await page.getByLabel('更多工具').click()
  await page.getByRole('button', { name: '切换全屏' }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)
  await expect(page.getByRole('alert')).toHaveCount(0)
})

